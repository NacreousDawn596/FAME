def main() -> None:
    parser = argparse.ArgumentParser(description="FAME multi-instance deployer")
    parser.add_argument("--no-build", action="store_true", help="skip docker image rebuilds")
    parser.add_argument("--fresh", action="store_true", help="drop volumes before starting (fresh DB -> clean organizer accounts)")
    parser.add_argument("--per-instance-bridges", action="store_true", help="one WhatsApp bridge per instance (default: single shared bridge)")
    parser.add_argument("--down", action="store_true", help="stop and remove all stacks + services")
    args = parser.parse_args()

    if not CSV_PATH.exists():
        print(f"error: {CSV_PATH} not found", file=sys.stderr)
        sys.exit(1)

    instances = read_instances()
    home = home_instance(instances)
    apps = app_instances(instances)

    if args.down:
        for inst in apps:
            docker_compose_down(inst["name"])
            subprocess.run(["systemctl", "--user", "disable", "--now", f"cloudflared-{inst['name']}.service"])
        if home:
            subprocess.run(["systemctl", "--user", "disable", "--now", "cloudflared-fame.service"])
            subprocess.run(["systemctl", "--user", "disable", "--now", "fame-home.service"])
        print("done.")
        return

    credentials_list: list[dict] = []

    # 1. Build + start each isolated app stack.
    for idx, inst in enumerate(apps):
        # WhatsApp bridge: shared by default (one number for all); per-instance
        # only with --per-instance-bridges (ports must be in the firewall list).
        bridge_port = (3000 + idx) if args.per_instance_bridges else SHARED_BRIDGE_PORT
        previous = load_env(inst["name"]) if not args.fresh else {}
        env, creds = build_app_env(inst, bridge_port, previous)
        env_path = write_env(inst["name"], env)
        credentials_list.append(creds)
        print(f"[{inst['name']}] generated {env_path}")
        if args.fresh:
            print(f"  → {inst['name']}: dropping volumes (fresh DB)")
            subprocess.run(
                ["docker", "compose", "-f", str(COMPOSE_FILE), "-p", inst["name"], "down", "-v"],
                cwd=ROOT,
            )
        docker_compose(inst["name"], env_path, build=not args.no_build)
        install_cloudflared_service(inst["name"], inst["token"])

    # 2. Home screen (static) + its tunnel.
    generate_home(instances)
    if home:
        install_home_service(home["port"])
        install_cloudflared_service("fame", home["token"])

    # 3. Print organizer credentials.
    print()
    print("=" * 62)
    print(" DEPLOY COMPLETE")
    print("=" * 62)
    for c in credentials_list:
        print()
        print(f"  {c['name']}  ({c['company']})  →  {c['url']}")
        print(f"    organizer email    : {c['email']}")
        print(f"    organizer username : {c['username']}")
        print(f"    organizer password : {c['password']}")
        print(f"    login              : {c['url']}/#/login")
        print(f"    whatsapp bridge    : host port {c['whatsapp_bridge_port']}")
    if home:
        print()
        print(f"  home screen → https://fame.{BASE_DOMAIN} (localhost:{home['port']})")
    print("=" * 62)


if __name__ == "__main__":
    main()
