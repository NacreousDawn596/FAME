"""FAME multi-instance deployer.

Single source of truth: ``instances.csv`` with columns ``name,port,cloudflared_token``.

For every row the deployer:

  * ``name == "fame"`` → the landing/home screen (static page served locally + tunnel).
  * anything else         → a full, fully-isolated FAME stack (docker compose project).

No per-instance ``.env`` files are hand-maintained: each stack's environment is
generated into ``.run/<name>.env`` from shared defaults plus unique per-instance
secrets (session secret, VAPID keypair, organizer password). Each instance gets
its own organizer account (``<slug>@gadzarts.xyz`` + a generated password printed
here) and its own company name, ports and Cloudflare tunnel.

Usage::

    python3 deploy.py            # generate env, build/start stacks, tunnels, home page
    python3 deploy.py --no-build # skip image rebuilds
    python3 deploy.py --down     # stop and remove every stack + tunnels

Requirements: docker + docker compose v2, cloudflared, openssl (key generation).
"""

